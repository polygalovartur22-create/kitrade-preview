import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectDir = path.dirname(fileURLToPath(import.meta.url));
const sources = [
  "styles.css",
  "premium.css",
  "reference-hero.css",
  "adaptive-v2.css",
  "responsive.css",
  "adaptive-final.css",
  "tilda-autoscale.css",
];

const sourceCss = sources
  .map((name) => `\n/* SOURCE: ${name} */\n${fs.readFileSync(path.join(projectDir, name), "utf8")}`)
  .join("\n");

function findBlockEnd(css, openIndex) {
  let depth = 1;
  let quote = "";
  let inComment = false;

  for (let index = openIndex + 1; index < css.length; index += 1) {
    const character = css[index];
    const next = css[index + 1];

    if (inComment) {
      if (character === "*" && next === "/") {
        inComment = false;
        index += 1;
      }
      continue;
    }

    if (!quote && character === "/" && next === "*") {
      inComment = true;
      index += 1;
      continue;
    }

    if (quote) {
      if (character === "\\" && next) {
        index += 1;
      } else if (character === quote) {
        quote = "";
      }
      continue;
    }

    if (character === "'" || character === "\"") {
      quote = character;
    } else if (character === "{") {
      depth += 1;
    } else if (character === "}") {
      depth -= 1;
      if (depth === 0) return index;
    }
  }

  throw new Error(`Unclosed CSS block at ${openIndex}`);
}

function splitMediaQueries(query) {
  const parts = [];
  let depth = 0;
  let start = 0;

  for (let index = 0; index < query.length; index += 1) {
    const character = query[index];
    if (character === "(") depth += 1;
    if (character === ")") depth -= 1;
    if (character === "," && depth === 0) {
      parts.push(query.slice(start, index).trim());
      start = index + 1;
    }
  }

  parts.push(query.slice(start).trim());
  return parts.filter(Boolean);
}

function resolveMediaBranch(branch, viewport) {
  let matches = true;
  let remaining = branch;

  remaining = remaining.replace(
    /\(\s*(min|max)-(width|height)\s*:\s*([0-9.]+)px\s*\)/gi,
    (_, bound, axis, rawValue) => {
      const actual = axis.toLowerCase() === "width" ? viewport.width : viewport.height;
      const expected = Number(rawValue);
      const passes = bound.toLowerCase() === "min" ? actual >= expected : actual <= expected;
      if (!passes) matches = false;
      return "";
    },
  );

  remaining = remaining
    .replace(/\s+and\s+(?=\s*(?:and\b|$))/gi, " ")
    .replace(/^\s*and\s+/i, "")
    .replace(/\s+and\s*$/i, "")
    .replace(/\s{2,}/g, " ")
    .trim();

  if (!matches) return null;
  if (!remaining || remaining === "all" || remaining === "screen") return "";
  return remaining;
}

function compile(css, viewport) {
  let output = "";
  let cursor = 0;

  while (cursor < css.length) {
    const openIndex = css.indexOf("{", cursor);
    const semicolonIndex = css.indexOf(";", cursor);

    if (openIndex === -1) {
      output += css.slice(cursor);
      break;
    }

    if (semicolonIndex !== -1 && semicolonIndex < openIndex) {
      output += css.slice(cursor, semicolonIndex + 1);
      cursor = semicolonIndex + 1;
      continue;
    }

    const header = css.slice(cursor, openIndex);
    const closeIndex = findBlockEnd(css, openIndex);
    const content = css.slice(openIndex + 1, closeIndex);
    const mediaIndex = header.toLowerCase().lastIndexOf("@media");

    if (mediaIndex >= 0) {
      const leading = header.slice(0, mediaIndex);
      const query = header.slice(mediaIndex + 6).trim();
      const resolved = splitMediaQueries(query)
        .map((branch) => resolveMediaBranch(branch, viewport))
        .filter((branch) => branch !== null);

      output += leading;
      if (resolved.some((branch) => branch === "")) {
        output += compile(content, viewport);
      } else if (resolved.length) {
        output += `@media ${resolved.join(", ")} {${compile(content, viewport)}}`;
      }
    } else {
      output += `${header}{${content}}`;
    }

    cursor = closeIndex + 1;
  }

  return output;
}

function freezeViewportUnits(css, viewport) {
  return css.replace(
    /(-?(?:\d+|\d*\.\d+))(dvh|svh|lvh|vh|dvw|svw|lvw|vw)\b/gi,
    (_, rawValue, unit) => {
      const value = Number(rawValue);
      const axis = unit.toLowerCase().endsWith("vw") ? viewport.width : viewport.height;
      return `${Number(((value * axis) / 100).toFixed(4))}px`;
    },
  );
}

const targets = [
  { query: "(max-width: 599px)", width: 390, height: 844 },
  { query: "(min-width: 600px) and (max-width: 1199px)", width: 834, height: 1194 },
  { query: "(min-width: 1200px)", width: 1920, height: 1080 },
];

const output = [
  "/* Generated by build-artboard-css.mjs. Do not edit by hand. */",
  ...targets.map(
    (target) =>
      `\n@media ${target.query} {\n${freezeViewportUnits(compile(sourceCss, target), target)}\n}`,
  ),
].join("\n");

fs.writeFileSync(path.join(projectDir, "artboard-compiled.css"), output);
console.log(`Generated artboard-compiled.css (${Buffer.byteLength(output)} bytes)`);
